/**
 * Generates a throwaway deployer key and writes it into `.env.deploy`.
 *
 *   npm run deployer:new
 *
 * Robinhood's own deployment guide recommends a throwaway key rather than
 * reusing a real wallet, and this exists so following that advice does not mean
 * exporting a private key by hand and pasting it around.
 *
 * Two things keep the secret contained. It is never printed — it goes from the
 * generator straight to disk and only the address reaches your screen, so it
 * cannot end up in a terminal scrollback, a screenshot or a chat log. And it
 * goes to `.env.deploy` rather than `.env`, because Next.js auto-loads `.env`
 * and Turbopack copies what it loads into `.next/cache`; see load-env.mjs.
 *
 * Both files are gitignored. Fund the printed address, then deploy.
 */

import { appendFileSync, existsSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
import { DEPLOY_ENV_FILE } from "./load-env.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ENV_FILE = DEPLOY_ENV_FILE;

const existing = existsSync(ENV_FILE) ? readFileSync(ENV_FILE, "utf8") : "";

// Overwriting a funded deployer would strand whatever is on it, and the key
// would be unrecoverable — there is no copy anywhere else by design.
if (/^\s*DEPLOYER_PRIVATE_KEY=\S/m.test(existing)) {
  const account = privateKeyToAccount(
    existing.match(/^\s*DEPLOYER_PRIVATE_KEY=(\S+)/m)[1],
  );

  console.log(`\n.env.deploy already has a deployer key.`);
  console.log(`address  ${account.address}`);
  console.log(`\nDelete that line from .env.deploy first if you really want a new one.\n`);
} else {
  const privateKey = generatePrivateKey();
  const account = privateKeyToAccount(privateKey);

  appendFileSync(
    ENV_FILE,
    `${existing && !existing.endsWith("\n") ? "\n" : ""}` +
      `# Throwaway deployer generated by scripts/new-deployer.mjs.\n` +
      `# Testnet funds only. Never commit this file, and keep it out of .env —\n` +
      `# Next.js loads that one and Turbopack copies it into .next/cache.\n` +
      `DEPLOYER_PRIVATE_KEY=${privateKey}\n`,
  );

  console.log(`\nWrote a new deployer key to .env.deploy (gitignored, not printed here).`);
  console.log(`\naddress  ${account.address}`);
  console.log(`
Next: put some Robinhood Chain Testnet ETH on that address. There is no faucet,
so it is bridged from Ethereum — https://docs.robinhood.com/chain/bridging

A deploy costs roughly 0.001 ETH at current gas. Then:

  RPC_URL=https://rpc.testnet.chain.robinhood.com npm run contracts:deploy
`);
}
